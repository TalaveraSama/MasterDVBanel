# ---------------------------------------------------------------------------
# Formato DVBv5 real
# ---------------------------------------------------------------------------
def test_parse_astra_19_2e_real():
    transponders = satxml.parse_tables_text(ASTRA_19_2E, name="Astra-19.2E")
    assert len(transponders) == 1
    transponder = transponders[0]
    assert transponder.delivery_system == "DVB-S2"
    assert transponder.frequency_khz == 11_362_000
    assert transponder.symbol_rate_ksps == 22_000
    assert transponder.polarization == "H"
    assert transponder.fec == "2/3"
    assert transponder.sat_position == "19.2E"


def test_parse_dvb_t_real():
    transponders = satxml.parse_tables_text(DVB_T_MADRID, name="es-Madrid")
    assert len(transponders) == 1
    transponder = transponders[0]
    assert transponder.delivery_system == "DVB-T"
    assert transponder.frequency_khz == 570_000
    assert transponder.bandwidth_mhz == 8
    assert transponder.code_rate_hp == "2/3"
    assert transponder.code_rate_lp == "NONE"
    assert transponder.modulation == "QAM_64"
    assert transponder.transmission_mode == "8K"
    assert transponder.guard_interval == "1/4"
    assert transponder.hierarchy == "NONE"
    assert transponder.sat_position is None


def test_parse_dvbv5_multiples_bloques_y_crlf():
    texto = ASTRA_19_2E.replace("\n", "\r\n")
    texto += (
        "[CHANNEL]\r\n"
        "\tDELIVERY_SYSTEM = DVBS2\r\n"
        "\tFREQUENCY = 12551500\r\n"
        "\tPOLARIZATION = VERTICAL\r\n"
        "\tSYMBOL_RATE = 22000000\r\n"
        "\tINNER_FEC = 5/6\r\n"
        "\tMODULATION = QPSK\r\n"
        "\tROLLOFF = 0.25\r\n"
        "\tPILOT = ON\r\n"
        "\tSTREAM_ID = 3\r\n"
    )
    transponders = satxml.parse_tables_text(texto, name="Astra-19.2E")
    assert [x.frequency_khz for x in transponders] == [11_362_000, 12_551_500]
    segundo = transponders[1]
    assert segundo.polarization == "V"
    assert segundo.fec == "5/6"
    assert segundo.modulation == "QPSK"
    assert segundo.rolloff == "0.25"
    assert segundo.pilot == "ON"
    assert segundo.stream_id == 3


def test_parse_dvbv5_con_bom():
    texto = "\ufeff" + ASTRA_19_2E
    assert len(satxml.parse_tables_text(texto, name="Astra-19.2E")) == 1


