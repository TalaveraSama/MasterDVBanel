def test_count_transponders(tablas):
    assert satxml.count_transponders(tablas / "dvb-s" / "Astra-19.2E") == 1
    assert satxml.count_transponders(tablas / "dvb-t" / "es-Madrid") == 1
    assert satxml.count_transponders(tablas / "no-existe") == 0


def test_load_bundle_y_load_bundles(tablas):
    bundle = satxml.load_bundle(tablas / "dvb-s" / "Astra-19.2E")
    assert len(bundle) == 1 and bundle[0].frequency_khz == 11_362_000

    bundles = satxml.load_bundles(tablas)
    assert set(bundles) == {"Astra-19.2E", "es-Madrid"}
    assert len(bundles["es-Madrid"]) == 1


def test_list_tables(tablas):
    tablas_disponibles = satxml.list_tables(tablas)
    nombres = [x["name"] for x in tablas_disponibles]
    assert nombres == ["Astra-19.2E", "es-Madrid"]
    astra = next(x for x in tablas_disponibles if x["name"] == "Astra-19.2E")
    assert astra["sat_position"] == "19.2E"
    assert astra["transponders"] == 1
    assert str(astra["path"]).endswith("Astra-19.2E")
    madrid = next(x for x in tablas_disponibles if x["name"] == "es-Madrid")
    assert madrid["sat_position"] is None


def test_bundle_names_y_find_table(tablas):
    assert satxml.bundle_names(tablas) == ["Astra-19.2E", "es-Madrid"]
    assert satxml.find_table("Astra-19.2E", tablas).name == "Astra-19.2E"
    assert satxml.find_table("es-Madrid", tablas).name == "es-Madrid"
    assert satxml.find_table("Astra-19.2E.conf", tablas) is None
    assert satxml.find_table("no-existe", tablas) is None
    # Por ruta directa
    directo = satxml.find_table(str(tablas / "dvb-t" / "es-Madrid"), tablas)
    assert directo is not None and directo.name == "es-Madrid"


def test_tablas_del_sistema_si_existen():
    base = pathlib.Path("/usr/share/dvb")
    if not base.is_dir():
        pytest.skip("sin dtv-scan-tables en este sistema")
    tablas = satxml.list_tables(base)
    assert tablas, "debe haber tablas instaladas"
    assert all(item["name"] for item in tablas)  # pragma: no cover - host Linux


def test_que_la_tabla_real_del_host_parsea():
    astra = pathlib.Path("/usr/share/dvb/dvb-s/Astra-19.2E")
    if not astra.is_file():
        pytest.skip("sin la tabla Astra-19.2E")
    transponders = satxml.parse_tables_file(astra)
    assert transponders
    for transponder in transponders:
        assert transponder.delivery_system in ("DVB-S", "DVB-S2")
        assert transponder.frequency_khz > 10_000_000
        assert transponder.symbol_rate_ksps and transponder.symbol_rate_ksps > 1000
        assert transponder.sat_position == "19.2E"


def test_delivery_system_normalizado():
    assert t.normalize_delivery_system("DVBS2") == "DVB-S2"
